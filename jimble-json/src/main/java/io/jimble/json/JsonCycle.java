package io.jimble.json;

/**
 * 書いている途中で循環参照を見つけたときの動き（D-307）
 *
 * <p>
 * 循環は「書いている途中の祖先に、同じオブジェクトがもう一度出てきた」ときだけを言う。
 * 同じオブジェクトが別の枝に2回出てくるのは循環ではないので、両方に中身を書く。
 * 比べるのは参照そのもの（{@code ==}）で、ハッシュの値ではない。
 * </p>
 */
public enum JsonCycle {

	/** 例外にする（どこで循環したかを載せる）。新しい入口の既定 */
	THROW,

	/** 空にする（オブジェクト・Map・Bean は {@code {}}、List・配列は {@code []}）。Dson の既定（作り直す前と同じ） */
	EMPTY,

	/** {@code null} を書く */
	NULL

}
